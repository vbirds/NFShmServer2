//先用简单的处理吧，后续看有没需要加其它算法

/**
 * @brief 数据加密函数
 * 
 * 使用XOR算法对数据进行加密，包括：
 * - 遍历数据缓冲区
 * - 对每个字节进行XOR运算
 * - 使用全局密钥进行加密
 * - 支持任意长度数据
 * - 高性能加密处理
 * 
 * @param pChar 要加密的数据缓冲区指针
 * @param length 数据长度
 */
void Encryption(char* pChar, int length);

/**
 * @brief 数据解密函数
 * 
 * 使用XOR算法对数据进行解密，包括：
 * - 遍历数据缓冲区
 * - 对每个字节进行XOR运算
 * - 使用全局密钥进行解密
 * - 支持任意长度数据
 * - 高性能解密处理
 * 
 * @param pChar 要解密的数据缓冲区指针
 * @param length 数据长度
 */
void Decryption(char* pChar, int length);
